/**
 * Universal Translation Helper Function
 * @param {string} key - Nested dot notation key e.g. 'nav.home' or 'hero.title'
 * @param {string} lang - Language code ('en', 'kn', 'hi')
 * @param {string} fallback - Optional fallback text if key is not found
 * @returns {string} Translated string
 */
export const t = (key, lang = 'en', fallback = '') => {
  if (!key) return fallback || '';
  const currentLang = (lang === 'kn' || lang === 'hi') ? lang : 'en';
  const parts = key.split('.');

  // Attempt lookup in chosen language
  let current = TRANSLATIONS[currentLang];
  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      current = undefined;
      break;
    }
  }

  if (typeof current === 'string') return current;

  // Fallback to English if not found in target language
  if (currentLang !== 'en') {
    let enCurrent = TRANSLATIONS.en;
    for (const part of parts) {
      if (enCurrent && typeof enCurrent === 'object' && part in enCurrent) {
        enCurrent = enCurrent[part];
      } else {
        enCurrent = undefined;
        break;
      }
    }
    if (typeof enCurrent === 'string') return enCurrent;
  }

  return fallback || key;
};
